#!/usr/bin/env python3
"""
Build the compact bilingual lexicon used by the in-browser Heidi scorer.

Input : src/assets/data/heidi_part1_side_by_side.json  (the only Heidi dataset)
        Ding de-en stem lexicon (scripts/heidi_lexicon.py, GPL; not shipped)
Output: src/app/heidi-analysis/scoring/heidi-lexicon.data.ts

The lexicon is a *method resource*, not data: for every German content word that
occurs in Part I it stores the Snowball-English stems of its Ding translations,
restricted to stems that occur in Stork's English (the only stems a coverage
check can ever match, so the restriction is lossless). It also stores the
Snowball-English stem of every English content word, so the browser needs no
stemmer and reproduces scripts/heidi_lexicon.py Bilex.coverage() exactly.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from heidi_lexicon import Bilex, de_content, en_content, en_stem, DE_STOP, EN_STOP, TOKEN_RE  # noqa: E402
import heidi_build_dataset as A  # noqa: E402
from heidi_align import SPEAKERS, SPEECH_VERBS_DE, SPEECH_VERBS_EN  # noqa: E402

SRC = os.path.join(HERE, '..', 'src', 'assets', 'data', 'heidi_part1_side_by_side.json')
OUT = os.path.join(HERE, '..', 'src', 'app', 'heidi-analysis', 'scoring', 'heidi-lexicon.data.ts')


def main():
    src = json.load(open(SRC, encoding='utf-8'))
    de_words, en_words = set(), set()
    for ch in src['chapters']:
        for r in ch['rows']:
            for p in r['de']:
                de_words |= set(de_content(p['text']))
            for p in r['en']:
                en_words |= set(en_content(p['text']))
    en_stem_of = {w: en_stem(w) for w in sorted(en_words)}
    stems = sorted(set(en_stem_of.values()))
    sidx = {s: i for i, s in enumerate(stems)}
    b = Bilex()
    de2en, cognate = {}, {}
    for w in sorted(de_words):
        t = sorted(b.translations(w) & sidx.keys())
        if t:
            de2en[w] = [sidx[s] for s in t]
        if len(w) > 3 and en_stem(w) in sidx:
            cognate[w] = sidx[en_stem(w)]
    data = {'stems': stems, 'en': {w: sidx[s] for w, s in en_stem_of.items()}, 'de': de2en, 'cognate': cognate}
    rules = {
        # exact copies of the Python method definitions (scripts/heidi_build_dataset.py, heidi_lexicon.py, heidi_align.py)
        'de_stop': sorted(DE_STOP), 'en_stop': sorted(EN_STOP), 'token_re': TOKEN_RE.pattern,
        'emo_de': A.EMO_DE, 'emo_en': A.EMO_EN, 'imagery': A.IMAGERY, 'culture': A.CULTURE,
        'diminutive_re': A.DIMINUTIVE_RE.pattern, 'dim_en_re': A.DIM_EN_RE.pattern, 'formal_re': A.FORMAL_RE.pattern,
        'sent_split': A.SENT_SPLIT.pattern,
        'speakers': [[c, l, d, e] for c, l, d, e in SPEAKERS],
        'speech_verbs_de': SPEECH_VERBS_DE, 'speech_verbs_en': SPEECH_VERBS_EN,
    }
    body = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('/* eslint-disable */\n// GENERATED by scripts/heidi_build_lexicon_ts.py — do not edit.\n'
                '// Ding de-en dictionary (Frank Richter, TU Chemnitz, GPL) restricted to the vocabulary of\n'
                '// heidi_part1_side_by_side.json; English stems: Snowball English. Indexes point into `stems`.\n'
                'export interface HeidiLexiconData { stems: string[]; en: Record<string, number>; de: Record<string, number[]>; cognate: Record<string, number>; }\n'
                f'export const HEIDI_LEXICON: HeidiLexiconData = {body};\n'
                '// Method rules (Python regex sources, converted to Unicode-aware JS regexes by heidi-scoring.ts).\n'
                'export interface HeidiRulesData { de_stop: string[]; en_stop: string[]; token_re: string; emo_de: Record<string, string>; emo_en: Record<string, string>;\n'
                '  imagery: [string, string][]; culture: [string, string, string, string][]; diminutive_re: string; dim_en_re: string; formal_re: string;\n'
                '  sent_split: string; speakers: [string, string, string[], string[]][]; speech_verbs_de: string; speech_verbs_en: string; }\n'
                f'export const HEIDI_RULES: HeidiRulesData = {json.dumps(rules, ensure_ascii=False, separators=(",", ":"))};\n')
    print(f'de words {len(de_words)} → {len(de2en)} with translations; en words {len(en_words)}; stems {len(stems)}; '
          f'{os.path.getsize(OUT)} bytes')


if __name__ == '__main__':
    main()
